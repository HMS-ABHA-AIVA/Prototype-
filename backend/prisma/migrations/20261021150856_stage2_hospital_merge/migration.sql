-- ---- Per-hospital running numbers --------------------------------------------------------------------------------------
-- The next number for one hospital and one series (MRN, bills, receipts ...). The row lock taken by the upsert makes two
-- concurrent callers get different numbers. `value` holds the last number issued; the first one issued is p_start.
CREATE OR REPLACE FUNCTION next_facility_number(p_facility text, p_key text, p_start integer) RETURNS integer
LANGUAGE sql AS $$
  INSERT INTO "FacilityCounter" ("facilityId", "key", "value") VALUES (p_facility, p_key, p_start)
  ON CONFLICT ("facilityId", "key") DO UPDATE SET "value" = "FacilityCounter"."value" + 1
  RETURNING "value"
$$;

-- Fills a numbered column on insert when it was left empty: TG_ARGV = column, prefix, series, first number.
CREATE OR REPLACE FUNCTION assign_facility_number() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF to_jsonb(NEW) ->> TG_ARGV[0] IS NULL THEN
    NEW := jsonb_populate_record(NEW, jsonb_build_object(TG_ARGV[0], TG_ARGV[1] || next_facility_number(NEW."facilityId", TG_ARGV[2], TG_ARGV[3]::integer)));
  END IF;
  RETURN NEW;
END
$$;

-- Every way a patient is created (registration, ABHA linking, Scan & Share, OPD desk) gets a medical record number.
CREATE TRIGGER "Patient_assign_mrn" BEFORE INSERT ON "Patient" FOR EACH ROW EXECUTE FUNCTION assign_facility_number('mrn', 'MRN-', 'mrn', '10001');
CREATE TRIGGER "Bill_assign_number" BEFORE INSERT ON "Bill" FOR EACH ROW EXECUTE FUNCTION assign_facility_number('billNo', 'BILL-', 'bill', '1001');
CREATE TRIGGER "OpdPayment_assign_number" BEFORE INSERT ON "OpdPayment" FOR EACH ROW EXECUTE FUNCTION assign_facility_number('receiptNo', 'OPD-', 'opd_receipt', '1001');
CREATE TRIGGER "Birth_assign_number" BEFORE INSERT ON "Birth" FOR EACH ROW EXECUTE FUNCTION assign_facility_number('birthNo', 'BR-', 'birth', '1');
CREATE TRIGGER "Purchase_assign_number" BEFORE INSERT ON "Purchase" FOR EACH ROW EXECUTE FUNCTION assign_facility_number('purchaseNo', 'PUR-', 'purchase', '1');

-- Patients registered after stage 0 (by code that did not issue MRNs yet) get theirs now, oldest first.
DO $$
DECLARE r record;
BEGIN
  FOR r IN SELECT "id", "facilityId" FROM "Patient" WHERE "mrn" IS NULL ORDER BY "createdAt", "id" LOOP
    UPDATE "Patient" SET "mrn" = 'MRN-' || next_facility_number(r."facilityId", 'mrn', 10001) WHERE "id" = r."id";
  END LOOP;
END
$$;

